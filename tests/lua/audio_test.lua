-- fk.audio, fk/music.lua, fk/reverb.lua and settings/audio.lua (audio spec). Nothing is mixed in Lua tests,
-- so voices stay alive until stopped.
local music = require("fk.music")
local reverb = require("fk.reverb")
local audio = require("settings.audio")

local function fails(fn, pattern)
  local ok, err = pcall(fn)
  assert(not ok and tostring(err):find(pattern, 1, true), tostring(err))
end

return {
  ["sounds load, are cached and know their length"] = function()
    local scan = fk.audio.sound("sounds/scan.ogg")
    assert(scan == fk.audio.sound("sounds/scan.ogg"), "cached")
    assert(math.abs(scan:length() - 2.0) < 0.01, scan:length())
    fails(function() fk.audio.sound("sounds/none.ogg") end, "sound: sounds/none.ogg: cannot find the file")
    fails(function() fk.audio.sound("textures/test_ground.jpg") end, "not a WAV or OGG Vorbis file")
    fails(function() fk.audio.sound("../x.ogg") end, "is not a path inside data/")
  end,
  ["named sounds pick a variation; voices can be changed and stopped"] = function()
    local before = fk.audio.active()
    local id = fk.audio.play("footstep", { position = { 1, 0, 2 }, volume = 0.8 })
    assert(math.type(id) == "integer" and fk.audio.alive(id) and fk.audio.active() == before + 1)
    local loop = fk.audio.play(fk.audio.sound("sounds/wind_loop.ogg"), { loop = true, bus = "ambient", pan = -0.5 })
    fk.audio.set(loop, { volume = 0.3 })
    fk.audio.set(loop, { pitch = 1.2, position = { 0, 0, 0 } })
    fk.audio.stop(loop)
    fk.audio.stop(id, 0.5)
    assert(not fk.audio.alive(loop), "stopped at once")
    fk.audio.play("scan", { bus = "ui" }) -- a single file without variations
    fails(function() fk.audio.play("boing") end, "no sound named 'boing'")
    fails(function() fk.audio.play("Bad Name") end, "is not a sound name")
    fails(function() fk.audio.play("scan", { volume = 9 }) end, "'volume' must be a number from")
    fails(function() fk.audio.play("scan", { bus = "music" }) end, "no bus named 'music'")
    fails(function() fk.audio.play("scan", { position = { 1, 2 } }) end, "'position' must be a table of 3 numbers")
    fails(function() fk.audio.play("scan", { position = { 1, 2, "x" } }) end, "'position' must be a table of 3 numbers")
    fails(function() fk.audio.set(1, { pitch = 9 }) end, "'pitch' must be a number from")
  end,
  ["listener, buses and reverb"] = function()
    fk.audio.listener({ position = { 0, 2, 0 }, right = { 1, 0, 0 } })
    fk.audio.listener({})
    fails(function() fk.audio.listener({ right = { 1 } }) end, "'right' must be a table of 3 numbers")
    fk.audio.volume("master", 1)
    fk.audio.volume("music", 0.5)
    fails(function() fk.audio.volume("loud", 1) end, "no bus named 'loud'")
    fails(function() fk.audio.volume("sfx", 3) end, "the volume must be from 0 to 2")
    fk.audio.reverb({ room = 0.9, wet = 0.4 })
    fails(function() fk.audio.reverb({ room = 2 }) end, "'room' must be a number from")
  end,
  ["music tracks crossfade by situation"] = function()
    music.load({ surface = "music/surface.ogg", discovery = "music/discovery.ogg" })
    assert(#music.tracks == 2 and fk.audio.track_volume("surface") == 0)
    music.play("surface", 0)
    assert(fk.audio.track_volume("surface") == 1 and fk.audio.track_volume("discovery") == 0)
    music.play("discovery", 2)
    assert(music.current == "discovery" and fk.audio.track_volume("surface") == 1, "fades take time")
    music.play(nil)
    assert(fk.audio.track_volume("nothing") == nil)
    fails(function() fk.audio.fade("nothing", 1, 1) end, "no music track named 'nothing'")
    fails(function() fk.audio.music("x", "music/none.ogg") end, "cannot find the file")
    fails(function() fk.audio.music("x", "textures/test_ground.jpg") end, "not a readable OGG Vorbis file")
    fails(function() fk.audio.music("x", "/etc/passwd") end, "is not a path inside data/")
    fails(function() fk.audio.fade("surface", 5) end, "the volume must be from 0 to 2")
  end,
  ["reverb zones pick the smallest zone around the listener"] = function()
    reverb.clear()
    reverb.zone({ center = { 0, 0, 0 }, radius = 20, room = 0.6, damping = 0.5, wet = 0.2 })
    reverb.zone({ center = { 5, 0, 0 }, radius = 3, room = 0.9, damping = 0.2, wet = 0.4 })
    assert(reverb.update({ 5, 0, 1 }).room == 0.9, "inside both: the smaller")
    assert(reverb.update({ 5, 0, 1 }).room == 0.9, "unchanged")
    assert(reverb.update({ -10, 0, 0 }).room == 0.6, "the big zone")
    assert(reverb.update({ 100, 0, 0 }) == reverb.default, "outside every zone")
  end,
  ["audio settings are stored and applied"] = function()
    audio.load()
    audio.current.music = 0.25
    audio.save()
    audio.current = audio.defaults()
    assert(audio.load().music == 0.25)
    audio.current = audio.defaults()
    audio.save()
  end,
}
